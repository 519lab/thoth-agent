"""contract test: dockerfile chowns runtime node_modules trees to thoth

regression guard for #18800. the container drops privileges to the thoth
user (uid 10000) in entrypoint.sh; runtime code that touches node_modules
(e.g. the web dashboard / Playwright browser install) fails with EACCES
unless the runtime node_modules trees are owned by thoth.
"""
from __future__ import annotations

from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parents[2]
DOCKERFILE = REPO_ROOT / "Dockerfile"


def test_dockerfile_chowns_runtime_node_modules_to_thoth_user() -> None:
    text = DOCKERFILE.read_text()

    chown_lines = [
        line for line in text.splitlines()
        if "chown" in line and "thoth:thoth" in line
    ]
    assert chown_lines, (
        "Dockerfile must contain a chown -R thoth:thoth for the runtime "
        "node_modules trees; see #18800"
    )

    chown_block = "\n".join(chown_lines)

    # the runtime-mutable node_modules tree must be passed to the chown
    # command. /opt/thoth/web is intentionally excluded: it is build-time
    # only, because THOTH_WEB_DIST points at thoth_cli/web_dist for runtime.
    for required_path in ("/opt/thoth/node_modules",):
        assert required_path in chown_block, (
            f"{required_path} must be passed to a chown -R thoth:thoth "
            f"command in the Dockerfile (see #18800)"
        )
